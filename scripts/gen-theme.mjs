#!/usr/bin/env node
/**
 * 主题定制工具（token 覆盖 → 产物 CSS）—「主题定制工具化」的 token→产物 段。
 *
 * 背景：vcl-ui 主题 = CSS 变量（src/components/tokens.css 的 :root / :root[data-theme='dark']
 * 双块）+ useTheme() 运行时切换。定制主题的正确姿势是「覆盖令牌」而不是改库 CSS——
 * 手写覆盖时两个坑：① 令牌名打错 → var() 静默失效（check:css-tokens 只查库内不查宿主）；
 * ② 暗色块忘写 → 切暗色后定制色被库的暗色值盖回。本工具把两件事锁死：
 *   - 令牌名必须 ∈ tokens.css 声明集（打错直接报错并给近似候选）
 *   - 配置分 light/dark 双块，产物同时出 :root 与 :root[data-theme='dark'] 两段覆盖
 *
 * 用法：
 *   node scripts/gen-theme.mjs [config.json] [out.css]   # 默认 theme.config.json → dist/theme.css
 *   node scripts/gen-theme.mjs --init                    # 生成 theme.config.json 模板
 *
 * 配置格式（JSON，全量键；空对象 = 该主题块不出产物段）：
 *   {
 *     "light": { "--color-primary": "#0f766e", "--space-4": "12px" },
 *     "dark":  { "--color-primary": "#14b8a6" }
 *   }
 *
 * 宿主引入顺序（产物追加在库 CSS 之后才覆盖得动）：
 *   import 'vcl-ui/dist/vcl-ui.css'
 *   import 'vcl-ui/dist/theme.css'
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs'
import { dirname, join, resolve } from 'path'
import { fileURLToPath } from 'url'
import process from 'process'

const ROOT = resolve(process.cwd())

// ---------- 纯函数（可单测，勿塞 IO） ----------

/** 从 tokens.css 文本提取声明集：任意位置的 `--name:` 声明（:root/暗色/media 各块均带缩进，
 *  不能按行首匹配；取并集即合法令牌全集） */
export function parseTokenNames(cssText) {
  const names = new Set()
  for (const m of cssText.matchAll(/--([a-z][a-z0-9-]*)\s*:/g)) names.add('--' + m[1])
  return names
}

/** 近似候选（编辑距离 ≤2 的令牌名，防打错拼写） */
export function suggestTokens(name, tokenNames, limit = 5) {
  const target = name.toLowerCase()
  const out = []
  for (const t of tokenNames) {
    if (!t.startsWith('--')) continue
    const d = editDistance(target, t)
    if (d <= 2) out.push([d, t])
  }
  out.sort((a, b) => a[0] - b[0] || a[1].localeCompare(b[1]))
  return out.slice(0, limit).map(([_d, t]) => t)
}

function editDistance(a, b) {
  const m = a.length
  const n = b.length
  if (!m) return n
  if (!n) return m
  // dp[i][j] = 前 i 个字符与前 j 个字符的距离；基线 dp[i][0]=i、dp[0][j]=j
  const dp = Array.from({ length: m + 1 }, (_, i) => new Array(n + 1).fill(0).map((_, j) => (i === 0 ? j : j === 0 ? i : 0)))
  for (let i = 1; i <= m; i++) {
    for (let j = 1; j <= n; j++) {
      dp[i][j] = Math.min(
        dp[i - 1][j] + 1,
        dp[i][j - 1] + 1,
        dp[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1),
      )
    }
  }
  return dp[m][n]
}

/** 校验配置：返回 { errors, normalized }。errors 非空即非法。
 *  规则：① 结构必须是 { light?, dark? } 且各为 对象；② 键必须是 --name 形式；
 *  ③ 令牌名 ∈ 声明集（给近似候选）；④ 值：非空字符串、无 `;{}"` 注入字符。 */
export function validateThemeConfig(config, tokenNames) {
  const errors = []
  const normalized = { light: {}, dark: {} }
  if (typeof config !== 'object' || config === null || Array.isArray(config)) {
    errors.push('配置根必须是对象 { "light": {...}, "dark": {...} }')
    return { errors, normalized }
  }
  for (const block of ['light', 'dark']) {
    if (config[block] === undefined) continue
    if (typeof config[block] !== 'object' || config[block] === null || Array.isArray(config[block])) {
      errors.push(`${block} 块必须是「令牌名 → 值」对象，实际是 ${typeof config[block]}`)
      continue
    }
    for (const [name, value] of Object.entries(config[block])) {
      if (!/^--[a-z][a-z0-9-]*$/.test(name)) {
        errors.push(`「${name}」不是合法令牌名（须 --kebab-case 小写）`)
        continue
      }
      if (!tokenNames.has(name)) {
        const near = suggestTokens(name, tokenNames)
        errors.push(`「${name}」未在 tokens.css 声明${near.length ? `（相近：${near.join('、')}）` : ''}——打错的令牌 var() 会静默失效`)
        continue
      }
      if (typeof value !== 'string' || !value.trim()) {
        errors.push(`「${name}」的值必须是非空字符串`)
        continue
      }
      if (/[;{}"]/u.test(value)) {
        errors.push(`「${name}」的值含 ;{}" 注入字符，拒绝生成`)
        continue
      }
      normalized[block][name] = value.trim()
    }
  }
  return { errors, normalized }
}

/** 渲染主题 CSS：light → :root；dark → :root[data-theme='dark']（暗色块与库的暗色块同特异性靠后覆盖） */
export function renderThemeCss(normalized) {
  const lines = [
    '/* vcl-ui theme override — generated by scripts/gen-theme.mjs, 勿手改（改 theme.config.json 重新生成） */',
  ]
  const seg = (sel, vars) => {
    if (!Object.keys(vars).length) return []
    return [`${sel} {`, ...Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`), '}']
  }
  lines.push(...seg(':root', normalized.light))
  lines.push(...seg(":root[data-theme='dark']", normalized.dark))
  if (lines.length === 1) lines.push('/* 空主题：light/dark 均未配置 */')
  return lines.join('\n') + '\n'
}

// ---------- CLI ----------

function readTokenNames() {
  const tokensCss = readFileSync(join(ROOT, 'src/components/tokens.css'), 'utf8')
  return parseTokenNames(tokensCss)
}

function main() {
  const args = process.argv.slice(2)
  if (args.includes('--init')) {
    const tpl = {
      light: {
        // 示例（取消注释启用）：换主色只需覆盖 4 个联动令牌，暗色块记得给暗色版
        // "--color-primary": "#0f766e",
        // "--color-primary-rgb": "15, 118, 110",
        // "--color-primary-hover": "#0d5f55",
        // "--color-primary-light": "#ecfdf5",
      },
      dark: {},
    }
    const cfgPath = join(ROOT, 'theme.config.json')
    writeFileSync(cfgPath, JSON.stringify(tpl, null, 2) + '\n')
    console.log(`✅ 已生成 ${cfgPath}（填入覆盖令牌后运行 node scripts/gen-theme.mjs）`)
    return
  }
  const cfgPath = resolve(ROOT, args[0] ?? 'theme.config.json')
  const outPath = resolve(ROOT, args[1] ?? 'dist/theme.css')
  if (!existsSync(cfgPath)) {
    console.error(`❌ 找不到配置 ${cfgPath}（node scripts/gen-theme.mjs --init 生成模板）`)
    process.exit(1)
  }
  let config
  try {
    config = JSON.parse(readFileSync(cfgPath, 'utf8'))
  } catch (e) {
    console.error(`❌ 配置不是合法 JSON：${e.message}`)
    process.exit(1)
  }
  const { errors, normalized } = validateThemeConfig(config, readTokenNames())
  if (errors.length) {
    console.error(`❌ 主题配置校验失败（${errors.length} 处）：`)
    errors.forEach((e) => console.error('  - ' + e))
    process.exit(1)
  }
  const total = Object.keys(normalized.light).length + Object.keys(normalized.dark).length
  if (total === 0) {
    console.log('⚠️ light/dark 均为空对象——仍生成占位产物（宿主可安全引入）')
  }
  mkdirSync(dirname(outPath), { recursive: true })
  writeFileSync(outPath, renderThemeCss(normalized))
  console.log(`✅ 主题产物 ${outPath}（light ${Object.keys(normalized.light).length} / dark ${Object.keys(normalized.dark).length} 项覆盖）`)
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  main()
}
